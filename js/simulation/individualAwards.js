/**
 * Performance-driven individual awards.
 *
 * Awards are decided by comparing the user's season evidence with a field of
 * rival players in the same competition edition - never by OVR gates or
 * unseeded dice. All randomness comes from an explicit seeded `rng`.
 *
 * Awards: Golden Boot, Golden Glove, Team of the Season, Player of the Season,
 * Young Player of the Season, Rookie (breakthrough) of the Season, World Player
 * of the Year. Every award is evaluated independently, so one player can win
 * several in the same season (e.g. Golden Boot + Player of the Season + Team of
 * the Season) and World Player of the Year never suppresses another award.
 *
 * Statuses: "nominated" (shortlisted), "selected" (Team of the Season slot),
 * "won". Records carry a stable `eventId`, so re-evaluating a season yields the
 * same ids and callers can dedupe.
 *
 * ---------------------------------------------------------------------------
 * NPC competitor model (approximation)
 * ---------------------------------------------------------------------------
 * The engine does not simulate individual stats for other players. The smallest
 * persistent model that keeps the awards honest is generated by
 * `ensureCompetitionAwardField`:
 *
 *   - Every club in the competition table gets a 15-man key-player roster
 *     (11 starters + 4 rotation players across GK/DEF/MID/FWD).
 *   - Team goals (`goalsFor`) are shared among that roster by a multinomial draw
 *     weighted by position scoring rates x minutes x a per-player talent factor,
 *     so every team has a plausible top scorer and totals stay consistent with the
 *     table (8% of goals go to unmodelled squad players). Assists use ~72% of
 *     team goals; clean sheets follow a Poisson-zero estimate from goalsAgainst.
 *   - Ratings, ages and prior senior minutes are drawn from simple priors.
 *   - Draw order is fixed and independent of the user's season: every club,
 *     including the user's own, is generated first from its own forked stream.
 *     Only afterwards is the user's club adjusted for consistency (the user's
 *     roster slot is removed and teammates are capped to `teamGoals - userGoals`).
 *     No threshold is ever set by looking at what the user needs to win.
 *   - The field is stored on `player.awardFields[editionId]` (plain JSON), so
 *     save/resume reads the same rivals instead of regenerating them. Only the
 *     strongest rivals per category are kept to bound save size, and only the
 *     latest few seasons are retained.
 *   - Rival names are placeholders ("<Club> ST1"), not real people.
 *   - Callers that already have rival stats can pass `rivals` to
 *     `evaluateSeasonAwards` (see `normalizeSuppliedRivals`) instead.
 */

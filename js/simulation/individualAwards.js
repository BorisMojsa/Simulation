/**
 * Evaluate every award for the user against competitor fields.
 *
 * @param {object} args
 * @param {object} args.player
 * @param {object} [args.evidence]       from buildSeasonEvidence (built from empty data if omitted)
 * @param {object} [args.standing]       user's league table row
 * @param {object} [args.league]
 * @param {Map}    [args.leagueLookup]   league name -> league (used if `league` is omitted)
 * @param {object[]} [args.table]        full league table (else a table is synthesised from the league)
 * @param {object} [args.rivals]         externally supplied rival stats (skips generation)
 * @param {object[]} [args.trophies]
 * @param {object} [args.rng]            seeded rng (defaults to a stream keyed by career + season)
 * @param {string} [args.seasonId]
 * @param {number} [args.seasonStartAge] age at the start of the season (not after ageing)
 * @param {object} [args.options]        formation, youthMaxAge, goldenBootScope, competitionEditionId, priorSeasons, ...
 * @returns {{seasonId, records, awardNames, byAward, decisionTrace, wins, selections, nominations, fields}}
 */
export function evaluateSeasonAwards({
  player,
  evidence: evidenceIn,
  standing = null,
  league = null,
  leagueLookup = null,
  table = null,
  rivals: suppliedRivals = null,
  trophies = [],
  rng = null,
  seasonId: seasonIdIn,
  seasonStartAge,
  options = {},
} = {}) {
  if (!player) throw new TypeError("evaluateSeasonAwards requires a player");
  const cfg = { ...AWARD_CONFIG, ...options };
  const seasonId = seasonIdIn ?? evidenceIn?.seasonId ?? `season-${player.seasons?.length ?? 0}`;
  const resolvedLeague = league || (player.club?.league && leagueLookup?.get?.(player.club.league)) || null;
  if (!evidenceIn) {
    throw new TypeError(
      "evaluateSeasonAwards requires evidence from buildSeasonEvidence (pass evidence to avoid a circular module load)",
    );
  }
  const evidence = evidenceIn;
  const playerId = playerIdOf(player, evidence);
  const group = roleGroupOf(evidence.position ?? player.position);
  const formation = FORMATIONS[cfg.formation] || FORMATIONS["4-3-3"];
  const age = num(seasonStartAge ?? evidence.seasonStartAge ?? player.age, null);
  const records = [];
  /** Every category gets an entry, including rejected / ineligible outcomes. */
  const decisionTrace = Object.fromEntries(
    AWARD_ORDER.map((awardId) => [
      awardId,
      { awardId, status: "pending", reason: null, rank: null, cutoff: null, evidence: null },
    ])
  );
  const trace = (awardId, patch) => {
    decisionTrace[awardId] = { ...decisionTrace[awardId], ...patch, awardId };
  };

  const bootScope = competitionScopeOf(cfg.goldenBootScope ?? "league");
  const leagueCompetitionKey =
    cfg.competitionKey ||
    resolvedLeague?.leagueId ||
    player.club?.leagueId ||
    player.playingLeagueId ||
    null;
  const leagueEditionId =
    cfg.competitionEditionId ??
    resolveCompetitionEditionId(evidence, "league", { seasonId, competitionKey: leagueCompetitionKey });
  const bootEditionId =
    bootScope === "league"
      ? leagueEditionId
      : resolveCompetitionEditionId(evidence, bootScope, { seasonId, competitionKey: cfg.competitionKey || null });

  const leagueLine = editionLine(evidence, leagueEditionId, "league");
  const ppg = teamPpgOf(standing, evidence);
  const total = evidence.total || { goals: evidence.goals, assists: evidence.assists, cleanSheets: evidence.cleanSheets };

  const ensure = (editionId, scope, lineForUser, tableIn) =>
    ensureCompetitionAwardField(
      player,
      {
        seasonId,
        competitionEditionId: editionId,
        scope,
        table: tableIn,
        league: resolvedLeague,
        standing,
        userClub: player.club,
        user: { goals: lineForUser.goals, assists: lineForUser.assists, position: evidence.position ?? player.position },
      },
      rng
    );

  const leagueField = suppliedRivals
    ? normalizeSuppliedRivals(suppliedRivals, leagueEditionId)
    : ensure(leagueEditionId, "league", leagueLine, table);
  const possibleMinutes = leagueField.possibleMinutes || 38 * 90;
  const leagueRivals = leagueField.rivals;

  const userLeagueEntry = {
    id: playerId,
    name: player.name ?? "You",
    isUser: true,
    group,
    position: evidence.position,
    age,
    minutes: num(leagueLine.minutes),
    matches: num(leagueLine.appearances),
    goals: num(leagueLine.goals),
    assists: num(leagueLine.assists),
    cleanSheets: leagueLine.cleanSheets,
    // League awards use the league-edition rating only — never whole-season combined rating.
    rating: leagueLine.rating ?? null,
    ratedMinutes: leagueLine.ratedMinutes ?? null,
    teamPpg: ppg,
    priorSeniorMinutes: priorSeniorMinutesOf(player, seasonId, cfg.priorSeasons),
  };

  const push = (def, editionId, scope, status, rank, shared, ev, reason = null, cutoff = null) => {
    records.push(makeRecord({ def, seasonId, editionId, scope, playerId, status, rank, shared, evidence: ev }));
    trace(def.awardId, { status, reason: reason || status, rank, cutoff, evidence: ev });
  };

  /* 1. Golden Boot ------------------------------------------------- */
  {
    const def = AWARD_DEFS.goldenBoot;
    const field =
      bootScope === "league"
        ? leagueField
        : ensure(bootEditionId, bootScope, editionLine(evidence, bootEditionId, bootScope), cfg.competitionTables?.[bootEditionId] ?? null);
    const line = editionLine(evidence, bootEditionId, bootScope);
    const goals = num(line.goals);
    const entries = [...field.rivals.map((r) => ({ id: r.id, name: r.name, goals: r.goals })), { id: playerId, name: userLeagueEntry.name, goals }];
    const st = standingOf(entries, playerId, (e) => e.goals);
    const leaderGoals = Math.max(...entries.map((e) => e.goals));
    const ev = {
      goals,
      scope: bootScope,
      leaderGoals,
      fieldSize: field.rivals.length + 1,
      tiedWith: st.tied.map((t) => t.name),
      top: sortDesc(entries, (e) => e.goals).slice(0, 5).map((e) => ({ name: e.name, goals: e.goals })),
    };
    if (goals > 0 && goals === leaderGoals) {
      push(def, bootEditionId, bootScope, "won", st.rank, st.shared, ev, "led-or-tied-goals", cfg.goldenBootShortlist);
    } else if (goals > 0 && st.rank <= cfg.goldenBootShortlist) {
      push(def, bootEditionId, bootScope, "nominated", st.rank, st.shared, ev, "within-shortlist", cfg.goldenBootShortlist);
    } else if (goals <= 0) {
      trace(def.awardId, { status: "ineligible", reason: "zero-goals", rank: st.rank, cutoff: cfg.goldenBootShortlist, evidence: ev });
    } else {
      trace(def.awardId, { status: "rejected", reason: "outside-shortlist", rank: st.rank, cutoff: cfg.goldenBootShortlist, evidence: ev });
    }
  }

  /* 2. Golden Glove ------------------------------------------------ */
  {
    const def = AWARD_DEFS.goldenGlove;
    const minMinutes = cfg.goldenGloveMinParticipation * possibleMinutes;
    const userEligible = group === "GK" && userLeagueEntry.cleanSheets != null && userLeagueEntry.minutes >= minMinutes;
    if (userEligible) {
      const entries = leagueRivals
        .filter((r) => r.group === "GK" && r.minutes >= minMinutes)
        .map((r) => ({ id: r.id, name: r.name, cleanSheets: r.cleanSheets }));
      entries.push({ id: playerId, name: userLeagueEntry.name, cleanSheets: num(userLeagueEntry.cleanSheets) });
      const st = standingOf(entries, playerId, (e) => e.cleanSheets);
      const leader = Math.max(...entries.map((e) => e.cleanSheets));
      const cs = num(userLeagueEntry.cleanSheets);
      const ev = {
        cleanSheets: cs,
        leaderCleanSheets: leader,
        minutes: userLeagueEntry.minutes,
        minimumMinutes: Math.round(minMinutes),
        fieldSize: entries.length,
        tiedWith: st.tied.map((t) => t.name),
        top: sortDesc(entries, (e) => e.cleanSheets).slice(0, 5).map((e) => ({ name: e.name, cleanSheets: e.cleanSheets })),
      };
      if (cs > 0 && cs === leader) {
        push(def, leagueEditionId, "league", "won", st.rank, st.shared, ev, "led-or-tied-clean-sheets", cfg.goldenBootShortlist);
      } else if (cs > 0 && st.rank <= cfg.goldenBootShortlist) {
        push(def, leagueEditionId, "league", "nominated", st.rank, st.shared, ev, "within-shortlist", cfg.goldenBootShortlist);
      } else if (cs <= 0) {
        trace(def.awardId, { status: "rejected", reason: "zero-clean-sheets", rank: st.rank, cutoff: cfg.goldenBootShortlist, evidence: ev });
      } else {
        trace(def.awardId, { status: "rejected", reason: "outside-shortlist", rank: st.rank, cutoff: cfg.goldenBootShortlist, evidence: ev });
      }
    } else {
      const reason =
        group !== "GK"
          ? "not-goalkeeper"
          : userLeagueEntry.cleanSheets == null
            ? "missing-clean-sheet-evidence"
            : "below-participation";
      trace(def.awardId, {
        status: "ineligible",
        reason,
        rank: null,
        cutoff: Math.round(minMinutes),
        evidence: { minutes: userLeagueEntry.minutes, minimumMinutes: Math.round(minMinutes), group },
      });
    }
  }

  /* 3. Team of the Season ------------------------------------------ */
  const scored = (entry) => scoreSeasonLine(lineOf(entry), possibleMinutes);
  const minMinutesTots = cfg.minParticipation * possibleMinutes;
  {
    const def = AWARD_DEFS.teamOfSeason;
    const pool = [...leagueRivals, userLeagueEntry].filter((e) => e.group === group && e.minutes >= minMinutesTots);
    const ranked = sortDesc(pool, scored);
    const idx = ranked.findIndex((e) => e.isUser);
    const slots = formation[group];
    if (idx >= 0) {
      const me = ranked[idx];
      const ev = {
        score: Number(scored(me).toFixed(3)),
        roleGroup: group,
        formation: cfg.formation,
        slots,
        goals: me.goals,
        assists: me.assists,
        cleanSheets: me.cleanSheets,
        rating: me.rating,
        minutes: me.minutes,
        poolSize: ranked.length,
      };
      if (idx < slots) {
        push(def, leagueEditionId, "league", "selected", idx + 1, false, ev, "within-formation-slots", slots);
      } else if (idx < slots + 3) {
        push(def, leagueEditionId, "league", "nominated", idx + 1, false, ev, "within-nomination-band", slots + 3);
      } else {
        trace(def.awardId, { status: "rejected", reason: "outside-nomination-band", rank: idx + 1, cutoff: slots + 3, evidence: ev });
      }
    } else {
      trace(def.awardId, {
        status: "ineligible",
        reason: userLeagueEntry.minutes < minMinutesTots ? "below-participation" : "not-in-role-pool",
        rank: null,
        cutoff: Math.round(minMinutesTots),
        evidence: { minutes: userLeagueEntry.minutes, roleGroup: group, poolSize: pool.length },
      });
    }
  }

  /* 4-6. POTS / Young POTS / Rookie ---------------------------------- */
  // Group-standardised so positions with big raw outputs do not swamp keepers/defenders.
  // Prefer full-population reference moments when present; else eligible retained rivals.
  const groupStats = {};
  for (const g of ["GK", "DEF", "MID", "FWD"]) {
    const ref = leagueField.referenceMoments?.byGroup?.[g];
    if (ref && Number.isFinite(ref.mean) && Number.isFinite(ref.sd)) {
      groupStats[g] = { mean: ref.mean, sd: Math.max(ref.sd, 0.35), source: "population" };
    } else {
      const scores = leagueRivals.filter((r) => r.group === g && r.minutes >= minMinutesTots).map((r) => scored(r));
      const mean = scores.length ? scores.reduce((s, v) => s + v, 0) / scores.length : 0;
      const sd = scores.length > 1 ? Math.sqrt(scores.reduce((s, v) => s + (v - mean) ** 2, 0) / (scores.length - 1)) : 1;
      groupStats[g] = { mean, sd: Math.max(sd, 0.35), source: "retained" };
    }
  }
  const potsMetric = (e) => (scored(e) - groupStats[e.group].mean) / groupStats[e.group].sd;

  // League POTS / Young / Rookie compare the same league-edition line as rivals.
  const eligible = (e) => (e.isUser ? userLeagueEntry.minutes : e.minutes) >= minMinutesTots;
  const candidatePool = [...leagueRivals, userLeagueEntry].filter(eligible);

  const rankedAward = (def, pool, extraEv = {}, eligibilityReason = null) => {
    const ranked = sortDesc(pool, potsMetric);
    const idx = ranked.findIndex((e) => e.isUser);
    if (idx < 0) {
      trace(def.awardId, {
        status: "ineligible",
        reason: eligibilityReason || "not-in-candidate-pool",
        rank: null,
        cutoff: cfg.shortlist,
        evidence: { poolSize: ranked.length, minutes: userLeagueEntry.minutes, ...extraEv },
      });
      return null;
    }
    const me = ranked[idx];
    const st = standingOf(ranked, playerId, potsMetric);
    const ev = {
      score: Number(scored(me).toFixed(3)),
      standardisedScore: Number(potsMetric(me).toFixed(3)),
      roleGroup: group,
      goals: me.goals,
      assists: me.assists,
      cleanSheets: me.cleanSheets,
      rating: me.rating,
      minutes: me.minutes,
      poolSize: ranked.length,
      leader: ranked[0].isUser ? null : { name: ranked[0].name, standardisedScore: Number(potsMetric(ranked[0]).toFixed(3)) },
      ...extraEv,
    };
    if (potsMetric(me) > 0) {
      if (st.rank === 1) push(def, leagueEditionId, "league", "won", st.rank, st.shared, ev, "standardised-leader", cfg.shortlist);
      else if (st.rank <= cfg.shortlist) {
        push(def, leagueEditionId, "league", "nominated", st.rank, st.shared, ev, "within-shortlist", cfg.shortlist);
      } else {
        trace(def.awardId, { status: "rejected", reason: "outside-shortlist", rank: st.rank, cutoff: cfg.shortlist, evidence: ev });
      }
    } else {
      trace(def.awardId, { status: "rejected", reason: "non-positive-standardised-score", rank: st.rank, cutoff: cfg.shortlist, evidence: ev });
    }
    return { st, ev, me };
  };

  const pots = rankedAward(
    AWARD_DEFS.playerOfSeason,
    candidatePool,
    {},
    userLeagueEntry.minutes < minMinutesTots ? "below-participation" : "not-in-candidate-pool"
  );
  if (age != null) {
    rankedAward(
      AWARD_DEFS.youngPlayer,
      candidatePool.filter((e) => e.age != null && e.age <= cfg.youthMaxAge),
      { age, maxAge: cfg.youthMaxAge },
      age > cfg.youthMaxAge ? "above-youth-max-age" : "not-in-youth-pool"
    );
  } else {
    trace(AWARD_DEFS.youngPlayer.awardId, {
      status: "ineligible",
      reason: "missing-season-start-age",
      rank: null,
      cutoff: cfg.youthMaxAge,
      evidence: null,
    });
  }
  {
    const isRookie = (e) =>
      e.priorSeniorMinutes < cfg.breakthroughPriorMinutesMax &&
      (e.isUser ? userLeagueEntry.minutes : e.minutes) >= cfg.breakthroughMinutes;
    const userIsRookie = isRookie(userLeagueEntry);
    rankedAward(
      AWARD_DEFS.rookie,
      candidatePool.filter(isRookie),
      {
        priorSeniorMinutes: userLeagueEntry.priorSeniorMinutes,
        requiredMinutes: cfg.breakthroughMinutes,
      },
      !userIsRookie
        ? userLeagueEntry.priorSeniorMinutes >= cfg.breakthroughPriorMinutesMax
          ? "prior-senior-minutes-exceeded"
          : "below-breakthrough-minutes"
        : "not-in-rookie-pool"
    );
  }

  /* 7. World Player of the Year ------------------------------------ */
  {
    const def = AWARD_DEFS.worldPlayer;
    const worldField = ensureWorldAwardField(player, { seasonId }, rng);
    const strength = Number.isFinite(evidence.competition?.competitionStrength) ? evidence.competition.competitionStrength : 0.5;
    const eliteTrophyWeight = (Array.isArray(evidence.trophies) ? evidence.trophies : [])
      .filter((t) => t.scope === "continental" || t.scope === "international" || t.kind === "continental" || t.kind === "international")
      .reduce((s, t) => s + num(t.participationWeight, 0.5), 0);
    const potsRank = pots?.st?.rank ?? null;
    // Explicit whole-season world line (documented broader evidence), separate from league awards.
    const userWorldEntry = {
      ...userLeagueEntry,
      minutes: Math.max(num(evidence.minutes), userLeagueEntry.minutes),
      goals: Math.max(num(total.goals), userLeagueEntry.goals),
      assists: Math.max(num(total.assists), userLeagueEntry.assists),
      cleanSheets: total.cleanSheets ?? userLeagueEntry.cleanSheets,
      rating: evidence.minutesWeightedRating ?? userLeagueEntry.rating,
    };
    const raw = scored(userWorldEntry);
    const champion = evidence.clubFinish && typeof evidence.clubFinish === "object" && evidence.clubFinish.champion;
    const worldScore = raw + 1.5 * (strength - 0.5) + 0.8 * eliteTrophyWeight + (champion ? 0.4 : 0);
    const gatePassed =
      potsRank != null &&
      potsRank <= cfg.worldMinLeagueRank &&
      strength >= cfg.worldMinCompetitionStrength &&
      userLeagueEntry.minutes >= cfg.minParticipation * possibleMinutes;
    const gateEv = {
      score: Number(worldScore.toFixed(3)),
      baseScore: Number(raw.toFixed(3)),
      competitionStrength: strength,
      eliteTrophyWeight: Number(eliteTrophyWeight.toFixed(3)),
      leagueRank: potsRank,
      bestRivalScore: worldField.candidates[0]?.score ?? null,
      worldMinLeagueRank: cfg.worldMinLeagueRank,
      worldMinCompetitionStrength: cfg.worldMinCompetitionStrength,
    };
    if (gatePassed) {
      const entries = [...worldField.candidates, { id: playerId, name: userLeagueEntry.name, score: worldScore }];
      const st = standingOf(entries, playerId, (e) => e.score);
      if (st.rank === 1) push(def, worldField.editionId, "world", "won", 1, st.shared, gateEv, "world-leader", cfg.shortlist);
      else if (st.rank <= cfg.shortlist) {
        push(def, worldField.editionId, "world", "nominated", st.rank, st.shared, gateEv, "within-shortlist", cfg.shortlist);
      } else {
        trace(def.awardId, { status: "rejected", reason: "outside-shortlist", rank: st.rank, cutoff: cfg.shortlist, evidence: gateEv });
      }
    } else {
      const reason =
        potsRank == null || potsRank > cfg.worldMinLeagueRank
          ? "league-pots-gate"
          : strength < cfg.worldMinCompetitionStrength
            ? "competition-strength-gate"
            : "below-participation";
      trace(def.awardId, { status: "ineligible", reason, rank: null, cutoff: cfg.worldMinLeagueRank, evidence: gateEv });
    }
  }

  const result = {
    seasonId,
    records,
    awardNames: awardRecordsToLegacyNames(records),
    byAward: Object.fromEntries(records.map((r) => [r.awardId, r])),
    decisionTrace,
    wins: records.filter((r) => r.status === "won"),
    selections: records.filter((r) => r.status === "selected"),
    nominations: records.filter((r) => r.status === "nominated"),
    fields: { league: leagueEditionId, world: `${seasonId}:world` },
  };
  if (cfg.attachRecognition !== false) attachRecognitionLocal(evidence, records);
  return result;
}


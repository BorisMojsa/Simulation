const num = (v, fallback = 0) => (v === null || v === undefined || v === "" || !Number.isFinite(Number(v)) ? fallback : Number(v));

export function roleGroupOf(position) {
  const pos = normalizePosition(position).position;
  if (pos === "GK") return "GK";
  if (["CB", "RB", "LB"].includes(pos)) return "DEF";
  if (["ST", "RW", "LW"].includes(pos)) return "FWD";
  return "MID";
}

function gaussian(rng) {
  const u1 = Math.max(rng.random(), 1e-9);
  const u2 = rng.random();
  return Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
}

function awardRng(rng, player, seasonId, label) {
  if (rng && typeof rng.fork === "function") return rng.fork(label); // fork does not advance the parent stream
  return createStreamRng(careerKey(player), `awards:${seasonId}:${label}`);
}

function playerIdOf(player, evidence) {
  return String(evidence?.playerId ?? player?.careerId ?? player?.id ?? player?.playerId ?? careerKey(player));
}

/** Competition ranking: 1 + number strictly better. `shared` when another entry has the same value. */
function standingOf(entries, id, valueOf) {
  const mine = entries.find((e) => e.id === id);
  if (!mine) return { rank: null, shared: false, tied: [] };
  const v = valueOf(mine);
  const eps = 1e-9;
  const better = entries.filter((e) => valueOf(e) > v + eps).length;
  const tied = entries.filter((e) => e.id !== id && Math.abs(valueOf(e) - v) <= eps);
  return { rank: better + 1, shared: tied.length > 0, tied };
}

function sortDesc(entries, valueOf) {
  return [...entries].sort((a, b) => valueOf(b) - valueOf(a) || String(a.id).localeCompare(String(b.id)));
}


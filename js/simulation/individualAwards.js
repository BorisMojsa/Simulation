function sameClub(row, club) {
  if (!row || !club) return false;
  return (club.clubId && row.clubId === club.clubId) || (club.name && row.name === club.name);
}

/** Deterministic stand-in table when the caller has none (keeps awards evaluable). */
function synthesizeTable(league, standing, userClub, rng) {
  const clubs = league?.clubs?.length ? league.clubs : Array.from({ length: 20 }, (_, i) => ({ name: `Club ${i + 1}` }));
  const n = Math.max(clubs.length, 8);
  const played = Math.min(46, 2 * (n - 1));
  const leagueOv = leagueOverallOf(league) ?? 70;
  const rows = clubs.slice(0, n).map((c, i) => {
    const strength = num(c.overall, leagueOv + 6 * gaussian(rng));
    const gpg = clamp(1.35 + 0.025 * (strength - leagueOv) + 0.12 * gaussian(rng), 0.7, 2.6);
    const apg = clamp(1.35 - 0.025 * (strength - leagueOv) + 0.12 * gaussian(rng), 0.6, 2.4);
    const goalsFor = Math.round(gpg * played);
    const goalsAgainst = Math.round(apg * played);
    const points = Math.round(clamp(1.35 + (0.9 * (goalsFor - goalsAgainst)) / played, 0.3, 2.8) * played);
    return { name: c.name ?? `Club ${i + 1}`, clubId: c.clubId ?? null, played, goalsFor, goalsAgainst, points, strength };
  });
  if (standing && userClub) {
    const idx = rows.findIndex((r) => sameClub(r, userClub));
    const replacement = {
      name: standing.name ?? userClub.name,
      clubId: standing.clubId ?? userClub.clubId ?? null,
      played: num(standing.played ?? standing.matches, played),
      goalsFor: num(standing.goalsFor),
      goalsAgainst: num(standing.goalsAgainst),
      points: num(standing.points),
      strength: num(standing.strength, leagueOv),
    };
    // Only trust the standing row if it carries real numbers.
    if (replacement.played > 0 && (standing.goalsFor != null || standing.points != null)) {
      if (idx >= 0) rows[idx] = replacement;
      else rows.push(replacement);
    }
  }
  rows.sort((a, b) => b.points - a.points || b.goalsFor - b.goalsAgainst - (a.goalsFor - a.goalsAgainst));
  return rows.map((r, i) => ({ ...r, position: i + 1 }));
}

function weightedPick(weights, rng) {
  const total = weights.reduce((s, w) => s + w, 0);
  if (!(total > 0)) return -1;
  let roll = rng.random() * total;
  for (let i = 0; i < weights.length; i++) {
    roll -= weights[i];
    if (roll <= 0) return i;
  }
  return weights.length - 1;
}

function generateTeamRoster(team, teamIdx, editionId, rng) {
  const played = Math.max(1, num(team.played, 38));
  const goalsFor = Math.max(0, num(team.goalsFor));
  const goalsAgainst = Math.max(0, num(team.goalsAgainst));
  const ppg = team.played > 0 ? num(team.points) / team.played : null;
  const teamQ = ppg == null ? 0 : (ppg / 3 - 0.45) * 2;

  const players = ROSTER.map(([pos, starter], slot) => {
    const u = starter ? 0.7 + 0.3 * rng.random() : 0.2 + 0.35 * rng.random();
    const talent = gaussian(rng);
    const ageNoise = gaussian(rng);
    const priorRoll = rng.random();
    const priorAmount = rng.random();
    const group = roleGroupOf(pos);
    const age = clamp(Math.round(26 + 4.2 * ageNoise), 17, 38);
    const rookieProb = age <= 22 ? 0.4 : age <= 24 ? 0.1 : 0.02;
    const priorSeniorMinutes =
      priorRoll < rookieProb ? Math.round(priorAmount * 800) : Math.round(1500 + priorAmount * 18000);
    // Appearances first; minutes must fit appearances × 90 (no invented ET for league rows).
    const matches = Math.max(0, Math.min(played, Math.round(played * u)));
    const minutes = Math.min(matches * 90, Math.round(played * 90 * u));
    const starts = Math.min(matches, starter ? matches : Math.max(0, Math.round(matches * 0.35)));
    return {
      id: `rival:${editionId}:${teamIdx}:${slot}`,
      name: `${team.name} ${pos}${slot + 1}`,
      club: team.name,
      clubId: team.clubId ?? null,
      position: pos,
      group,
      starter,
      age,
      u,
      talent,
      priorSeniorMinutes,
      minutes,
      matches,
      starts,
      goals: 0,
      assists: 0,
      cleanSheets: 0,
    };
  });

  // Goals: multinomial draw weighted by role x minutes x talent.
  const goalWeights = players.map((p) => (SCORING_WEIGHT[p.position] ?? 0.1) * p.u * Math.exp(0.45 * p.talent));
  const goalPool = Math.round(goalsFor * 0.92);
  for (let g = 0; g < goalPool; g++) {
    const i = weightedPick(goalWeights, rng);
    if (i >= 0) players[i].goals += 1;
  }
  const assistWeights = players.map((p) => (ASSIST_WEIGHT[p.position] ?? 0.1) * p.u * Math.exp(0.35 * p.talent));
  const assistPool = Math.round(goalsFor * 0.72 * 0.9);
  for (let a = 0; a < assistPool; a++) {
    const i = weightedPick(assistWeights, rng);
    if (i >= 0) players[i].assists += 1;
  }

  // Clean sheets: P(shutout) = Poisson zero given goals against per game.
  const pClean = Math.exp(-goalsAgainst / played);
  let teamCleanSheets = 0;
  for (let m = 0; m < played; m++) if (rng.random() < pClean) teamCleanSheets += 1;
  for (const p of players) {
    if (p.group !== "GK" && p.group !== "DEF") continue;
    for (let c = 0; c < teamCleanSheets; c++) if (rng.random() < p.u * 0.97) p.cleanSheets += 1;
    // A keeper/defender cannot earn more clean sheets than appearances.
    p.cleanSheets = Math.min(p.cleanSheets, p.matches);
  }

  // Ratings last, from the realised output. Baseline matches user `computeMatchRating` (6.0).
  // Persist the rating noise draw so post-cap recomputation keeps the same sample.
  for (const p of players) {
    p.ratingNoise = gaussian(rng);
    p.rating = rivalRatingFromOutput(p, teamQ, p.ratingNoise);
  }

  return { players, teamCleanSheets, ppg, position: team.position ?? null, teamQ };
}

function rivalRatingFromOutput(p, teamQ, noise = 0) {
  const w = ROLE_OUTPUT[p.group] || ROLE_OUTPUT.MID;
  const per90 = Math.max(p.minutes, 1) / 90;
  const out = (w.g * p.goals + w.a * p.assists + w.cs * p.cleanSheets) / per90;
  const talent = Number.isFinite(p.talent) ? p.talent : 0;
  // Role-aware centers: keepers sit under 6.0 without goals; defenders' clean-sheet
  // output must not push strong-talent peers far above matched user CB ratings.
  const isGk = p.group === "GK";
  const isDef = p.group === "DEF";
  const base = isGk ? RATING_BASELINE - 0.12 : isDef ? RATING_BASELINE : RATING_BASELINE + 0.06;
  const outCoef = isGk ? 0.05 : isDef ? 0.1 : 0.16;
  const talentCoef = isDef ? 0.06 : 0.1;
  return Number(
    clamp(base + 0.2 * teamQ + outCoef * out + talentCoef * talent + 0.1 * noise, 5.2, 8.2).toFixed(2)
  );
}

function adjustUserTeam(roster, userContext) {
  const { goals, assists, position, teamGoals } = userContext;
  // Remove the roster slot the user occupies (same position first, else the first starter of the group).
  const group = roleGroupOf(position);
  const norm = normalizePosition(position).position;
  let idx = roster.players.findIndex((p) => p.starter && p.position === norm);
  if (idx < 0) idx = roster.players.findIndex((p) => p.starter && p.group === group);
  if (idx < 0) idx = roster.players.findIndex((p) => p.group === group);
  if (idx >= 0) roster.players.splice(idx, 1);

  const cap = (key, limit) => {
    const total = roster.players.reduce((s, p) => s + p[key], 0);
    if (total <= limit) return;
    const scale = limit <= 0 ? 0 : limit / total;
    for (const p of roster.players) p[key] = Math.floor(p[key] * scale);
  };
  cap("goals", Math.max(0, num(teamGoals) - num(goals)));
  cap("assists", Math.max(0, Math.round(num(teamGoals) * 0.72) - num(assists)));
  // Recompute ratings after capping, retaining each player's original rating-noise draw.
  const teamQ = Number.isFinite(roster.teamQ)
    ? roster.teamQ
    : roster.ppg == null
      ? 0
      : (roster.ppg / 3 - 0.45) * 2;
  for (const p of roster.players) {
    const noise = Number.isFinite(p.ratingNoise) ? p.ratingNoise : 0;
    p.rating = rivalRatingFromOutput(p, teamQ, noise);
  }
}

function lineOf(r) {
  return { group: r.group, minutes: r.minutes, goals: r.goals, assists: r.assists, cleanSheets: r.cleanSheets, rating: r.rating, teamPpg: r.teamPpg };
}

/**
 * Retain rivals needed for every category decision using the same eligibility and
 * metrics as evaluation. Raw-score leaders who fail participation must not hide
 * eligible contenders.
 */
export function selectRivalIds(rivals, possibleMinutes, referenceMoments = null) {
  const keep = new Set();
  const add = (list, n) => list.slice(0, n).forEach((r) => keep.add(r.id));
  const score = (r) => scoreSeasonLine(lineOf(r), possibleMinutes);
  const minTots = AWARD_CONFIG.minParticipation * possibleMinutes;
  const minGlove = AWARD_CONFIG.goldenGloveMinParticipation * possibleMinutes;
  const moments = referenceMoments?.byGroup || {};
  const potsMetric = (r) => {
    const m = moments[r.group] || { mean: 0, sd: 1 };
    return (score(r) - m.mean) / Math.max(m.sd, 0.35);
  };

  // TOTS / role slots: participation-eligible, ranked by season score.
  for (const g of ["GK", "DEF", "MID", "FWD"]) {
    add(
      sortDesc(
        rivals.filter((r) => r.group === g && r.minutes >= minTots),
        score
      ),
      12
    );
  }
  // Golden Boot: goal leaders (no invented participation gate).
  add(sortDesc(rivals, (r) => r.goals), 12);
  // Golden Glove: participation-eligible keepers by clean sheets.
  add(
    sortDesc(
      rivals.filter((r) => r.group === "GK" && r.minutes >= minGlove),
      (r) => r.cleanSheets
    ),
    8
  );
  // POTS: participation-eligible by standardised score.
  add(
    sortDesc(
      rivals.filter((r) => r.minutes >= minTots),
      potsMetric
    ),
    12
  );
  // Young: start-age eligible + participation.
  add(
    sortDesc(
      rivals.filter(
        (r) => r.age != null && r.age <= AWARD_CONFIG.youthMaxAge && r.minutes >= minTots
      ),
      potsMetric
    ),
    10
  );
  // Rookie: prior-senior + breakthrough-minute eligibility.
  add(
    sortDesc(
      rivals.filter(
        (r) =>
          r.priorSeniorMinutes < AWARD_CONFIG.breakthroughPriorMinutesMax &&
          r.minutes >= AWARD_CONFIG.breakthroughMinutes
      ),
      potsMetric
    ),
    10
  );
  return keep;
}

export function buildReferenceMoments(rivals, possibleMinutes) {
  return buildReferenceMomentsInternal(rivals, possibleMinutes);
}

/** Full-population score moments for role standardization (retained before compacting). */
function buildReferenceMomentsInternal(rivals, possibleMinutes) {
  const minMins = AWARD_CONFIG.minParticipation * possibleMinutes;
  const byGroup = {};
  for (const g of ["GK", "DEF", "MID", "FWD"]) {
    const group = rivals.filter((r) => r.group === g);
    const eligible = group.filter((r) => r.minutes >= minMins);
    const scores = group.map((r) => scoreSeasonLine(lineOf(r), possibleMinutes));
    const n = scores.length;
    const mean = n ? scores.reduce((s, v) => s + v, 0) / n : 0;
    const sd = n > 1 ? Math.sqrt(scores.reduce((s, v) => s + (v - mean) ** 2, 0) / (n - 1)) : 1;
    byGroup[g] = { n, mean, sd: Math.max(sd, 0.35), eligibleN: eligible.length };
  }
  return {
    populationSize: rivals.length,
    byGroup,
    note: "Moments from the full generated population before top-contender retention.",
  };
}

function stripRival(r, { keepTalent = false } = {}) {
  const { u: _u, talent, starter: _starter, ratingNoise: _rn, ...rest } = r;
  if (keepTalent && Number.isFinite(talent)) return { ...rest, talent };
  return rest;
}

function fieldInputFingerprint(seasonContext, table, possibleMinutes) {
  const user = seasonContext.user || {};
  return {
    possibleMinutes: num(possibleMinutes),
    userGoals: num(user.goals),
    userAssists: num(user.assists),
    userPosition: user.position ?? null,
    teams: table.length,
    tablePlayedSum: table.reduce((s, r) => s + num(r.played), 0),
    tableGoalsForSum: table.reduce((s, r) => s + num(r.goalsFor), 0),
    tablePointsSum: table.reduce((s, r) => s + num(r.points), 0),
  };
}

function fingerprintsEqual(a, b) {
  if (!a || !b) return false;
  return JSON.stringify(a) === JSON.stringify(b);
}

/**
 * Reuse only when the supported lifecycle allows it.
 * - Final fields with matching fingerprint: reuse (idempotent).
 * - Partial fields: reuse only when fingerprint still matches; never lock a
 *   partial field across changed final inputs.
 * - Legacy v1 without stage: reuse only when stored possibleMinutes/userContext
 *   match the requested fingerprint (completed-history compatibility).
 */
function shouldReuseAwardField(existing, fingerprint) {
  if (!existing || !COMPATIBLE_FIELD_VERSIONS.has(existing.version)) return false;
  if (existing.stage === FIELD_STAGE_FINAL && fingerprintsEqual(existing.inputFingerprint, fingerprint)) {
    return true;
  }
  if (existing.stage === FIELD_STAGE_PARTIAL && fingerprintsEqual(existing.inputFingerprint, fingerprint)) {
    return true;
  }
  if (existing.version === 1 && existing.stage == null) {
    const legacy = {
      possibleMinutes: num(existing.possibleMinutes),
      userGoals: num(existing.userContext?.goals),
      userAssists: num(existing.userContext?.assists),
      userPosition: existing.userContext?.position ?? null,
      teams: num(existing.teams),
      tablePlayedSum: null,
      tableGoalsForSum: null,
      tablePointsSum: null,
    };
    // Legacy v1 lacks table sums — compare the overlapping keys only.
    return (
      legacy.possibleMinutes === fingerprint.possibleMinutes &&
      legacy.userGoals === fingerprint.userGoals &&
      legacy.userAssists === fingerprint.userAssists &&
      String(legacy.userPosition) === String(fingerprint.userPosition) &&
      legacy.teams === fingerprint.teams
    );
  }
  return false;
}

function pruneFields(player) {
  const keys = Object.keys(player.awardFields || {});
  const max = AWARD_CONFIG.fieldRetentionSeasons * 3;
  while (keys.length > max) delete player.awardFields[keys.shift()];
}

/**
 * Create (once) and return the rival field for a competition edition.
 *
 * @param {object} player  field is stored at `player.awardFields[editionId]`
 * @param {object} seasonContext
 * @param {string} seasonContext.seasonId
 * @param {string} [seasonContext.competitionEditionId]
 * @param {string} [seasonContext.scope="league"]
 * @param {object[]} [seasonContext.table]   rows {name, clubId?, played, goalsFor, goalsAgainst, points, position, strength}
 * @param {object}  [seasonContext.league]
 * @param {object}  [seasonContext.standing] user's table row
 * @param {object}  [seasonContext.userClub] {clubId, name}
 * @param {{goals:number, assists:number, position:string}} [seasonContext.user] user's output in this edition
 * @param {object} rng seeded rng (a fork is used; the parent stream is untouched)
 */
export function ensureCompetitionAwardField(player, seasonContext = {}, rng) {
  if (!player || typeof player !== "object") throw new TypeError("ensureCompetitionAwardField requires a player");
  const scope = competitionScopeOf(seasonContext.scope ?? "league");
  const seasonId = seasonContext.seasonId ?? "season";
  const editionId =
    seasonContext.competitionEditionId ??
    resolveCompetitionEditionId([], scope, { seasonId, competitionKey: seasonContext.league?.leagueId });
  if (!player.awardFields || typeof player.awardFields !== "object") player.awardFields = {};

  const stream = awardRng(rng, player, seasonId, `field:${editionId}`);
  const userClub = seasonContext.userClub || player.club || null;
  const standing = seasonContext.standing || null;
  const league = seasonContext.league || null;
  let table = Array.isArray(seasonContext.table) && seasonContext.table.length ? seasonContext.table : null;
  let tableApproximated = false;
  if (!table) {
    table = synthesizeTable(league, standing, userClub, stream.fork("table"));
    tableApproximated = true;
  }
  // Generated player lines / clean sheets are always synthetic approximations.
  const playerStatsApproximated = true;
  const possibleMinutes = Math.max(...table.map((r) => num(r.played, 38))) * 90;
  const stage =
    seasonContext.fieldStage === FIELD_STAGE_PARTIAL ? FIELD_STAGE_PARTIAL : FIELD_STAGE_FINAL;
  const fingerprint = fieldInputFingerprint(seasonContext, table, possibleMinutes);

  const existing = player.awardFields[editionId];
  if (shouldReuseAwardField(existing, fingerprint)) {
    // Upgrade a matching partial to final when the same inputs are finalized.
    if (existing.stage === FIELD_STAGE_PARTIAL && stage === FIELD_STAGE_FINAL) {
      existing.stage = FIELD_STAGE_FINAL;
    }
    return existing;
  }

  const user = seasonContext.user || {};
  // 1) Generate every club's roster, user's included, exactly as for any other club.
  const rosters = table.map((row, teamIdx) => ({
    row,
    isUserTeam: sameClub(row, userClub),
    roster: generateTeamRoster(row, teamIdx, editionId, stream.fork(`team:${teamIdx}`)),
  }));

  // 2) Adjust the user's club for consistency BEFORE selection so category retention
  //    uses post-cap ratings/output (opponents unchanged).
  let userTeamRow = null;
  for (const { row, isUserTeam, roster } of rosters) {
    if (!isUserTeam) continue;
    userTeamRow = row;
    adjustUserTeam(roster, {
      goals: user.goals,
      assists: user.assists,
      position: user.position ?? player.position,
      teamGoals: row.goalsFor,
    });
  }

  const flatten = () =>
    rosters.flatMap(({ roster, isUserTeam }) =>
      roster.players.map((p) => ({ ...p, teamPpg: roster.ppg, teamPosition: roster.position, userTeam: isUserTeam }))
    );
  const fullPopulation = flatten();
  // Reference moments from the full post-adjustment population.
  const referenceMoments = buildReferenceMomentsInternal(fullPopulation, possibleMinutes);
  // 3) Retain by actual category eligibility/metrics so compact ≡ full decisions.
  const keepIds = selectRivalIds(fullPopulation, possibleMinutes, referenceMoments);
  const rivals = fullPopulation.filter((r) => keepIds.has(r.id));
  const field = {
    version: FIELD_VERSION,
    stage,
    inputFingerprint: fingerprint,
    editionId,
    scope,
    seasonId,
    approximated: tableApproximated || playerStatsApproximated,
    tableApproximated,
    playerStatsApproximated,
    cleanSheetBasis: "poisson-approx",
    teams: table.length,
    possibleMinutes,
    populationSize: fullPopulation.length,
    referenceMoments,
    userContext: {
      clubId: userClub?.clubId ?? null,
      club: userClub?.name ?? null,
      goals: num(user.goals),
      assists: num(user.assists),
      position: user.position ?? player.position ?? null,
      teamGoals: userTeamRow ? num(userTeamRow.goalsFor) : null,
    },
    note: "Approximate NPC field: multinomial split of table goals, Poisson clean sheets, seeded priors. Placeholder names. Ratings use the shared 6.0 baseline. Compact retention uses category eligibility metrics.",
    rivals: sortDesc(rivals, (r) => r.goals).map((r) => stripRival(r)),
  };
  // Optional full-population export for matched parity / compaction audits (not save-path).
  if (seasonContext.retainDiagnosticPopulation) {
    field.diagnosticPopulation = fullPopulation.map((r) => stripRival(r, { keepTalent: true }));
    field.talentToAbility = {
      formula: "impliedOverall = clamp(70 + 12 * talent, 55, 95)",
      note: "Maps generation talent ~ N(0,1) onto an ability scale comparable to user rating/overall for matched cells.",
    };
  }
  player.awardFields[editionId] = field;
  pruneFields(player);
  return field;
}

/** World-class benchmark pool for World Player of the Year (seeded, user-independent). */
export function ensureWorldAwardField(player, { seasonId, fieldStage } = {}, rng) {
  if (!player.awardFields || typeof player.awardFields !== "object") player.awardFields = {};
  const editionId = `${seasonId ?? "season"}:world`;
  const stage = fieldStage === FIELD_STAGE_PARTIAL ? FIELD_STAGE_PARTIAL : FIELD_STAGE_FINAL;
  const sid = seasonId ?? "season";
  const fingerprint = { seasonId: sid, scope: "world" };
  const existing = player.awardFields[editionId];
  if (
    existing &&
    COMPATIBLE_FIELD_VERSIONS.has(existing.version) &&
    existing.scope === "world" &&
    fingerprintsEqual(existing.inputFingerprint || fingerprint, fingerprint) &&
    (existing.stage === FIELD_STAGE_FINAL || existing.stage == null || existing.stage === stage)
  ) {
    if (existing.stage === FIELD_STAGE_PARTIAL && stage === FIELD_STAGE_FINAL) existing.stage = FIELD_STAGE_FINAL;
    if (existing.stage == null && stage === FIELD_STAGE_FINAL) existing.stage = FIELD_STAGE_FINAL;
    return existing;
  }
  const stream = awardRng(rng, player, seasonId, `field:${editionId}`);
  // Synthetic world candidates scored with the same season-line contract (not an opaque 4.4 mean).
  const worldPossible = 38 * 90;
  const candidates = Array.from({ length: AWARD_CONFIG.worldCandidates }, (_, i) => {
    const groups = ["GK", "DEF", "MID", "FWD"];
    const group = groups[i % 4];
    const talent = 0.8 + 0.5 * Math.abs(gaussian(stream));
    const minutes = Math.round(worldPossible * (0.72 + 0.2 * stream.random()));
    const line = {
      group,
      minutes,
      goals: group === "FWD" ? Math.round(18 + 8 * talent) : group === "MID" ? Math.round(8 + 5 * talent) : group === "DEF" ? Math.round(2 + 2 * talent) : 0,
      assists: group === "GK" ? 0 : Math.round(4 + 6 * talent * (group === "MID" || group === "FWD" ? 1 : 0.4)),
      cleanSheets: group === "GK" || group === "DEF" ? Math.round(10 + 6 * talent) : 0,
      rating: Number((RATING_BASELINE + 0.55 + 0.35 * talent + 0.12 * gaussian(stream)).toFixed(2)),
      teamPpg: 1.8 + 0.4 * talent,
    };
    return {
      id: `rival:${editionId}:${i}`,
      name: `World candidate ${i + 1}`,
      group,
      score: Number(scoreSeasonLine(line, worldPossible).toFixed(3)),
      line,
    };
  }).sort((a, b) => b.score - a.score);
  const field = {
    version: FIELD_VERSION,
    stage,
    inputFingerprint: fingerprint,
    editionId,
    scope: "world",
    seasonId: sid,
    approximated: true,
    scoreUnits: "scoreSeasonLine",
    note: "Bounded synthetic world field in scoreSeasonLine units; not a full world simulation.",
    candidates,
  };
  player.awardFields[editionId] = field;
  pruneFields(player);
  return field;
}

/**
 * Convert an externally supplied rival block into a field.
 * Accepts the legacy shape `{ leagueScorers, leagueKeepers, leagueCandidates }`
 * or an already-built field (`{ rivals: [...] }`). Not persisted.
 */
export function normalizeSuppliedRivals(supplied, editionId, possibleMinutes = 38 * 90) {
  if (Array.isArray(supplied?.rivals)) return { possibleMinutes, ...supplied, editionId: supplied.editionId ?? editionId };
  const toEntry = (r, i, kind, group) => {
    const position = r.position || (group === "GK" ? "GK" : "ST");
    const g = group || roleGroupOf(position);
    const apps = num(r.appearances ?? r.matches, 34);
    const rating = r.rating != null ? Number(r.rating) : r.score != null ? clamp(5.5 + 0.022 * Number(r.score), 5.8, 8.2) : 6.6;
    return {
      id: String(r.playerId ?? r.id ?? `rival:${kind}:${i}`),
      name: r.name ?? `Rival ${kind} ${i + 1}`,
      position,
      group: g,
      age: r.age ?? null,
      minutes: num(r.minutes, apps * 85),
      matches: apps,
      goals: num(r.goals),
      assists: num(r.assists),
      cleanSheets: num(r.cleanSheets),
      rating,
      teamPpg: r.teamPpg ?? null,
      priorSeniorMinutes: num(r.priorSeniorMinutes, 20000),
    };
  };
  const rivals = [
    ...(supplied?.leagueScorers || []).map((r, i) => toEntry(r, i, "scorer")),
    ...(supplied?.leagueKeepers || []).map((r, i) => toEntry(r, i, "keeper", "GK")),
    ...(supplied?.leagueCandidates || []).map((r, i) => toEntry(r, i, "candidate")),
  ];
  const seen = new Set();
  return { version: FIELD_VERSION, editionId, scope: "league", approximated: false, possibleMinutes, rivals: rivals.filter((r) => !seen.has(r.id) && seen.add(r.id)) };
}


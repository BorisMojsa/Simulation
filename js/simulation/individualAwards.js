/**
 * Leaf helpers are inlined so this module has no import edge to seasonEvidence /
 * playerDevelopmentModel. That avoids Chromium "binding name is not found"
 * failures when main.js loads seasonSimulator with a cache-busting query string.
 */
function careerKey(player) {
  const explicit = player?.development?.careerId ?? player?.careerId;
  if (explicit !== undefined && explicit !== null && explicit !== "") return String(explicit);
  return `${player?.name ?? "player"}|${player?.nationality ?? ""}|${player?.startYear ?? ""}`;
}

function competitionScopeOf(typeOrKind, isInternational = false) {
  if (isInternational) return "international";
  const t = String(typeOrKind ?? "league").toLowerCase();
  if (["international", "nationalteam", "national", "nation"].includes(t)) return "international";
  if (["european", "continental", "europe", "champions-league", "uefa"].includes(t)) return "continental";
  if (["cup", "domestic-cup", "domesticcup", "domestic_cup", "playoff"].includes(t)) return "cup";
  if (t === "league") return "league";
  return "other";
}

function leagueOverallOf(league) {
  if (!league || typeof league !== "object") return null;
  const v = Number(league.overall ?? league.strength ?? league.avgOverall);
  return Number.isFinite(v) ? v : null;
}

function resolveCompetitionEditionId(evidenceOrEditions, scope = "league", { seasonId, competitionKey } = {}) {
  const editions = Array.isArray(evidenceOrEditions) ? evidenceOrEditions : evidenceOrEditions?.editions || [];
  const hit = editions.find((e) => e.scope === scope && (!competitionKey || e.competitionKey === competitionKey));
  if (hit?.editionId) return hit.editionId;
  const sid = seasonId ?? evidenceOrEditions?.seasonId ?? "season";
  return `${sid}:${scope}${competitionKey ? `:${competitionKey}` : ""}`;
}

function attachRecognitionLocal(evidence, records = []) {
  if (!evidence || !Array.isArray(evidence.recognition)) return evidence;
  if (Object.isFrozen(evidence.recognition)) return evidence;
  for (const rec of records) {
    if (!rec) continue;
    if (evidence.recognition.some((x) => x.eventId === rec.eventId)) continue;
    evidence.recognition.push(rec);
  }
  return evidence;
}


function editionLine(evidence, editionId, scope) {
  const byEdition = evidence.byEdition || {};
  if (editionId && byEdition[editionId]) return byEdition[editionId];
  // evidenceKey is competitionId::editionId; also accept a unique suffix match.
  if (editionId && !String(editionId).includes("::")) {
    const suffix = `::${editionId}`;
    const hits = Object.entries(byEdition).filter(([k]) => k.endsWith(suffix));
    if (hits.length === 1) return hits[0][1];
  }
  const scoped = evidence.byScope?.[scope];
  if (scoped) return scoped;
  // Hand-built evidence may only carry raw competition-type buckets.
  const raw = evidence.byCompetitionType || {};
  const key = scope === "continental" ? "european" : scope;
  const b = raw[key] || raw[scope];
  if (b) {
    return {
      minutes: num(b.minutes),
      appearances: num(b.appearances ?? b.apps),
      starts: num(b.starts),
      goals: num(b.goals),
      assists: num(b.assists),
      cleanSheets: b.cleanSheets ?? null,
    };
  }
  return { minutes: 0, appearances: 0, starts: 0, goals: 0, assists: 0, cleanSheets: null };
}

function teamPpgOf(standing, evidence) {
  const cf = evidence?.clubFinish && typeof evidence.clubFinish === "object" ? evidence.clubFinish : null;
  const played = num(standing?.played ?? standing?.matches ?? cf?.played);
  const points = standing?.points ?? cf?.points;
  return played > 0 && points != null ? num(points) / played : null;
}

function isSeniorSeason(s) {
  if (!s || !(num(s.minutes) > 0)) return false;
  if (s.academy || s.isAcademy || s.youth || s.isYouth || s.level === "youth" || s.phase === "academy") return false;
  return true;
}

/** Senior minutes from earlier seasons. Club moves do not reset it. Call before the current season is pushed. */
export function priorSeniorMinutesOf(player, seasonId, priorSeasons) {
  const seasons = Array.isArray(priorSeasons) ? priorSeasons : player?.seasons || [];
  return seasons
    .filter((s) => !(seasonId != null && s.seasonId != null && String(s.seasonId) === String(seasonId)))
    .filter(isSeniorSeason)
    .reduce((sum, s) => sum + num(s.minutes), 0);
}


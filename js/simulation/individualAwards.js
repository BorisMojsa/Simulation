/**
 * Legacy string[] for the UI: winners and selections only (nominations are not
 * honours). Pass `{ includeNominations: true }` for shortlist labels.
 */
function awardRecordsToLegacyNames(records = [], { includeNominations = false } = {}) {
  const wanted = new Set(includeNominations ? ["won", "selected", "nominated"] : ["won", "selected"]);
  const seen = new Set();
  const names = [];
  for (const r of [...records].sort((a, b) => AWARD_ORDER.indexOf(a.awardId) - AWARD_ORDER.indexOf(b.awardId))) {
    if (!wanted.has(r.status)) continue;
    const label = r.status === "nominated" ? `${r.label} (nominee)` : r.label;
    if (seen.has(label)) continue;
    seen.add(label);
    names.push(label);
  }
  return names;
}
export { awardRecordsToLegacyNames };

/**
 * Compatibility wrapper.
 *
 *   simulateIndividualAwards({ player, evidence, standing, ... })  -> string[] (with `.records`, `.result`)
 *   simulateIndividualAwards(performanceScore, season, player, leagueLookup, extra?) -> string[]
 *
 * The positional (legacy) form has no ledger, so evidence is approximated from
 * the season totals it receives: goals/assists/clean sheets are taken as league
 * output and minutes as `season.minutes` or ~78 per match. Pass `extra`
 * ({ evidence, standing, table, trophies, rng, seasonId, seasonStartAge }) to
 * use real data. The result is deterministic; there is no random fallback.
 */
export function simulateIndividualAwards(first, season, playerArg, leagueLookup, extra = {}) {
  // Sync wrapper: evidence must already be available (or first.evidence). Building
  // evidence pulls seasonEvidence.js and is done by seasonSimulator / tests.
  let result;
  if (first && typeof first === "object" && first.player) {
    if (!first.evidence) {
      throw new TypeError("simulateIndividualAwards({player}) requires evidence");
    }
    result = evaluateSeasonAwards(first);
  } else {
    const player = playerArg;
    if (!player) return Object.assign([], { records: [], result: null });
    const s = season || {};
    const seasonId = extra.seasonId ?? s.seasonId ?? `season-${s.seasonNumber ?? player.seasons?.length ?? 0}`;
    const league = extra.league ?? (s.league && leagueLookup?.get?.(s.league)) ?? null;
    const standing = extra.standing ?? s.standing ?? null;
    let evidence = extra.evidence;
    if (!evidence) {
      // Minimal evidence stub for legacy callers — avoids importing seasonEvidence.
      const apps = Math.max(0, num(s.matches));
      const minutes = num(s.minutes, Math.round(apps * 78));
      const goals = num(s.goals);
      const assists = num(s.assists);
      const cleanSheets = num(s.cleanSheets);
      evidence = {
        seasonId,
        playerId: careerKey(player),
        position: player.position,
        seasonStartAge: extra.seasonStartAge ?? s.age ?? player.age,
        minutes,
        appearances: apps,
        starts: apps,
        goals,
        assists,
        cleanSheets,
        ratedMinutes: minutes,
        minutesWeightedRating: s.avgMatchRating ?? null,
        seasonP: clamp((num(first, 60) - 70) / 30, -1, 1),
        reliability: clamp(apps / 30, 0.2, 1),
        recognition: [],
        trophies: extra.trophies || [],
        priorSeniorMinutes: priorSeniorMinutesOf(player, seasonId),
        byCompetitionType: {
          league: { minutes, appearances: apps, starts: apps, goals, assists, cleanSheets },
        },
        editions: [{ scope: "league", editionId: `${seasonId}:league` }],
      };
    }
    result = evaluateSeasonAwards({
      player,
      evidence,
      standing,
      league,
      leagueLookup,
      table: extra.table ?? null,
      trophies: extra.trophies || [],
      rng: extra.rng ?? createStreamRng(careerKey(player), `awards:${seasonId}`),
      seasonId,
      seasonStartAge: extra.seasonStartAge ?? s.age ?? player.age,
      options: extra.options,
    });
  }
  return Object.assign([...result.awardNames], { records: result.records, result });
}
